package com.example.croop.model;

public class OrderItem {
    private String item;
    private int price;

    // Getters and setters
    public String getItem() {
        return item;
    }

    public void setItem(String item) {
        this.item = item;
    }

    public int getQuantity() {
        return price;
    }

    public void setQuantity(int price) {
        this.price = price;
    }
}
